export const getBrochureById = (id) => {
    return brochuresData.find(doc => doc.id === id);
};

export const getBrochuresByType = (type) => {
    return brochuresData.filter(doc => doc.type === type);
};

export const getBrochuresByCategory = (category) => {
    return brochuresData.filter(doc => doc.category === category);
};

export const getFeaturedBrochures = () => {
    return brochuresData.filter(doc => doc.featured);
};

export const getMostDownloaded = (count = 5) => {
    return [...brochuresData]
        .sort((a, b) => b.downloadCount - a.downloadCount)
        .slice(0, count);
};
